def F(term, question, distractors, why):
    d = tuple(distractors)
    assert len(d) == 3, f"need 3 distractors, got {len(d)} for {term!r}"
    assert len({term, *d}) == 4, f"duplicate options for {term!r}"
    return {"t": term, "q": question, "d": list(d), "w": why}


