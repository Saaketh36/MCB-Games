def apply_enhancements(games):
    applied = 0
    for g in games:
        gid = g['id']
        for q_idx, q in enumerate(g.get('questions', [])):
            key = (gid, q_idx)
            if key in ENHANCEMENTS_C1_C2:
                q['options'] = ENHANCEMENTS_C1_C2[key]
                applied += 1
    return applied

